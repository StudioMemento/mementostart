// One source for the standalone bundle and first-paint shadow markup; no network/font/GPU dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { navMarkup } from '../public/navigation/render.mjs';
import { syncNavViewport } from '../public/navigation/viewport.mjs';
const root = resolve(import.meta.dirname, '..');
const dir = resolve(root, 'public/navigation');
const embed = value => {
  const file = value.split('/').at(-1).split('?')[0];
  return 'data:image/webp;base64,' + readFileSync(resolve(dir, 'assets', file)).toString('base64');
};
const files = ['core','blur','styles','icon-assets','memento-paths','wordmark','icons','render','viewport','navbar','child'];
const parts = files.map(file => {
  let text = readFileSync(resolve(dir, file + '.mjs'), 'utf8');
  text = text.replace(/^import .+ from .+;\s*$/gm, '').replace(/^export /gm, '');
  text = text.replace(/new URL\('([^']+)',import.meta.url\).href/g, (_, path) => JSON.stringify(embed(path)));
  return '// navigation/' + file + '.mjs\n' + text;
});
writeFileSync(resolve(dir,'start.bundle.js'), '/* Generated by scripts/build-navigation.mjs. */\n(()=>{\n"use strict";\n' + parts.join('\n') + '\ninstallChild({page:"start",hub:"https://mementostudio.it"});\n})();\n');
const markup = navMarkup('start').replace(/file:[^"<>]+\/([^/"<>]+-nav.webp[^"<>]*)/g, (_, path) => embed(path));
const boot = `(()=>{const host=document.querySelector('memento-nav'),template=host.querySelector('template[shadowrootmode]');if(!host.shadowRoot&&template){host.attachShadow({mode:'open'}).append(template.content);template.remove();}(${syncNavViewport.toString()})(host);})();`;
const htmlFile = resolve(root, 'index.html');
let html = readFileSync(htmlFile,'utf8');
html = html.replace(/<!-- MEMENTO_OVERLAY_START -->[\s\S]+?<!-- MEMENTO_OVERLAY_END -->/,
  `<!-- MEMENTO_OVERLAY_START -->\n<memento-nav active="start" mode="standalone" hub="https://mementostudio.it" data-memento-kit="12.1.0" data-memento-prerender><template shadowrootmode="open">${markup}</template></memento-nav>\n<script>${boot}</script>\n<!-- MEMENTO_OVERLAY_END -->`);
writeFileSync(htmlFile,html);
console.log('Navigation bundle and first-paint markup synchronized');
