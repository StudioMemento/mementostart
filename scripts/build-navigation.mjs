import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {navMarkup} from '../navigation/render.mjs';
import {iconAssets} from '../navigation/icon-assets.mjs?v=12.1.0';
const root=fileURLToPath(new URL('../',import.meta.url));
const data=path=>'data:image/webp;base64,'+readFileSync(path).toString('base64');
let markup=navMarkup('start');
for(const asset of Object.values(iconAssets))markup=markup.replaceAll(asset.src,data(fileURLToPath(asset.src)));
const shell=`<memento-nav active="start" mode="standalone" hub="https://mementostudio.it" data-memento-kit="12.1.0" data-memento-prerender>
<template shadowrootmode="open">${markup}</template>
</memento-nav>
<script>(()=>{const host=document.querySelector('memento-nav'),template=host.querySelector('template[shadowrootmode]');if(!host.shadowRoot&&template){host.attachShadow({mode:'open'}).append(template.content);template.remove();}})();</script>`;
let html=readFileSync(root+'index.html','utf8');
const marker=/<!-- MEMENTO_OVERLAY_START -->[\s\S]*?<!-- MEMENTO_OVERLAY_END -->/;
if(!marker.test(html))throw Error('Missing overlay render markers.');
html=html.replace(marker,'<!-- MEMENTO_OVERLAY_START -->\n'+shell+'\n<!-- MEMENTO_OVERLAY_END -->');
writeFileSync(root+'index.html',html);

// A single deferred file attaches behavior; the overlay already paints from HTML.
const modules=['core.mjs','blur.mjs','styles.mjs','icon-assets.mjs','memento-paths.mjs','wordmark.mjs','icons.mjs','render.mjs','navbar.mjs','child.mjs'];
const bundle=modules.map(file=>{
  let source=readFileSync(root+'navigation/'+file,'utf8');
  source=source.replace(/^import\s+.+?\s+from\s+['"].+?['"];\s*$/gm,'').replace(/\bexport (const|function|class) /g,'$1 ');
  source=source.replace(/new URL\(['"]\.\/assets\/([^'"]+)['"],\s*import\.meta\.url\)\.href/g,(_,asset)=>JSON.stringify(data(root+'navigation/assets/'+asset.split('?')[0])));
  if(source.includes('import.meta'))throw Error('Unresolved module URL: '+file);
  return '// navigation/'+file+'\n'+source;
}).join('\n');
writeFileSync(root+'navigation/start.bundle.js','/* Generated by scripts/build-navigation.mjs. */\n(()=>{\n"use strict";\n'+bundle+'\ninstallChild({page:"start",hub:"https://mementostudio.it"});\n})();\n');
console.log('Built initial overlay HTML and one deferred hydration bundle.');
